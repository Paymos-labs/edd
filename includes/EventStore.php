<?php

declare(strict_types=1);

namespace PaymosEasyDigitalDownloads;

use Paymos\Webhook\CommitAwareEventStoreInterface;

defined('ABSPATH') || exit;

final class EventStore implements CommitAwareEventStoreInterface
{
    private const SCHEMA_VERSION = '2';
    private const SCHEMA_OPTION = 'paymos_edd_event_schema_version';
    private $pendingHash = '';
    private $ownerToken = '';
    private $pendingTtlSeconds = 0;

    public static function activate($networkWide = false)
    {
        self::forEachBlog(static function () {
            self::install();
            self::scheduleCleanup();
        }, $networkWide);
    }

    public static function scheduleCleanup()
    {
        if (!wp_next_scheduled('paymos_edd_cleanup_events')) {
            wp_schedule_event(time() + 3600, 'daily', 'paymos_edd_cleanup_events');
        }
    }

    public static function deactivate($networkWide = false)
    {
        self::forEachBlog(static function () {
            wp_clear_scheduled_hook('paymos_edd_cleanup_events');
        }, $networkWide);
    }

    private static function forEachBlog(callable $callback, $networkWide)
    {
        if (!$networkWide || !is_multisite()) {
            $callback();
            return;
        }
        $offset = 0;
        do {
            $blogs = get_sites(array('fields' => 'ids', 'number' => 100, 'offset' => $offset));
            foreach ($blogs as $blogId) {
                switch_to_blog((int) $blogId);
                try {
                    $callback();
                } finally {
                    restore_current_blog();
                }
            }
            $offset += count($blogs);
        } while (count($blogs) === 100);
    }

    public static function install()
    {
        global $wpdb;
        self::requireDatabase();
        $table = self::tableName();
        $charset = method_exists($wpdb, 'get_charset_collate') ? $wpdb->get_charset_collate() : '';
        // Charset/collation come solely from wpdb; identifiers use WP 6.5's %i.
        // phpcs:disable WordPress.DB.DirectDatabaseQuery, WordPress.DB.PreparedSQL.InterpolatedNotPrepared, PluginCheck.Security.DirectDB.UnescapedDBParameter -- Versioned own-table schema; charset is generated by wpdb and table identifier uses %i.
        $created = $wpdb->query($wpdb->prepare("CREATE TABLE IF NOT EXISTS %i (
            event_hash varchar(32) NOT NULL,
            event_id varchar(191) NOT NULL,
            owner_token char(32) NOT NULL DEFAULT '',
            status varchar(16) NOT NULL,
            expires_at bigint unsigned NOT NULL,
            created_at bigint unsigned NOT NULL,
            updated_at bigint unsigned NOT NULL,
            PRIMARY KEY (event_hash), KEY expires_at (expires_at)
        ) {$charset}", $table));
        // phpcs:enable WordPress.DB.DirectDatabaseQuery, WordPress.DB.PreparedSQL.InterpolatedNotPrepared, PluginCheck.Security.DirectDB.UnescapedDBParameter
        if ($created === false) {
            throw new \RuntimeException('Paymos event storage is unavailable.');
        }
        // phpcs:ignore WordPress.DB.DirectDatabaseQuery -- Uncached native schema inspection during the versioned upgrade.
        $column = $wpdb->get_row($wpdb->prepare('SHOW COLUMNS FROM %i LIKE %s', $table, 'owner_token'), ARRAY_A);
        // phpcs:ignore WordPress.DB.DirectDatabaseQuery -- Versioned owner-token migration in the integration-owned table.
        if (!is_array($column) && $wpdb->query($wpdb->prepare("ALTER TABLE %i ADD owner_token char(32) NOT NULL DEFAULT ''", $table)) === false) {
            throw new \RuntimeException('Paymos event storage upgrade failed.');
        }
        update_option(self::SCHEMA_OPTION, self::SCHEMA_VERSION, false);
    }

    public function remember($eventId, $ttlSeconds)
    {
        global $wpdb;
        self::ensureTable();
        if ($this->pendingHash !== '') {
            throw new \RuntimeException('Paymos event reservation is already owned.');
        }
        self::purgeExpired();
        $hash = md5((string) $eventId);
        $now = time();
        $token = bin2hex(random_bytes(16));
        // phpcs:ignore WordPress.DB.DirectDatabaseQuery -- Unique-key acquisition must read durable SQL state without a cache.
        $inserted = $wpdb->query($wpdb->prepare(
            'INSERT IGNORE INTO %i (event_hash,event_id,owner_token,status,expires_at,created_at,updated_at) VALUES (%s,%s,%s,%s,%d,%d,%d)',
            self::tableName(), $hash, (string) $eventId, $token, 'processing', $now + 300, $now, $now
        ));
        if ($inserted === false) {
            throw new \RuntimeException('Paymos event reservation failed.');
        }
        if ($inserted !== 1) {
            // phpcs:ignore WordPress.DB.DirectDatabaseQuery -- Read the current owner for a fenced compare-and-swap, never a cached lease.
            $row = $wpdb->get_row($wpdb->prepare('SELECT owner_token,status,expires_at FROM %i WHERE event_hash=%s', self::tableName(), $hash), ARRAY_A);
            if (!is_array($row) || (int) $row['expires_at'] > $now) {
                return false;
            }
            // phpcs:ignore WordPress.DB.DirectDatabaseQuery -- Atomic takeover compares every observed lease version field.
            $inserted = $wpdb->query($wpdb->prepare(
                'UPDATE %i SET owner_token=%s,status=%s,expires_at=%d,updated_at=%d WHERE event_hash=%s AND owner_token=%s AND status=%s AND expires_at=%d AND expires_at<=%d',
                self::tableName(), $token, 'processing', $now + 300, $now, $hash,
                (string) $row['owner_token'], (string) $row['status'], (int) $row['expires_at'], $now
            ));
            if ($inserted === false) {
                throw new \RuntimeException('Paymos event reservation failed.');
            }
            if ($inserted !== 1) {
                return false;
            }
        }
        $this->pendingHash = $hash;
        $this->ownerToken = $token;
        $this->pendingTtlSeconds = max(1, (int) $ttlSeconds);
        return true;
    }

    public function isCommitted($eventId)
    {
        global $wpdb;
        self::ensureTable();
        // phpcs:ignore WordPress.DB.DirectDatabaseQuery -- Deduplication requires current committed state from SQL.
        $row = $wpdb->get_row($wpdb->prepare('SELECT status,expires_at FROM %i WHERE event_hash=%s', self::tableName(), md5((string) $eventId)), ARRAY_A);
        return is_array($row) && $row['status'] === 'committed' && (int) $row['expires_at'] > time();
    }

    public function commit()
    {
        global $wpdb;
        if ($this->pendingHash === '') {
            return;
        }
        self::requireDatabase();
        $now = time();
        // phpcs:ignore WordPress.DB.DirectDatabaseQuery -- Commit is fenced by this reservation owner and deadline.
        $updated = $wpdb->query($wpdb->prepare(
            'UPDATE %i SET status=%s,expires_at=%d,updated_at=%d WHERE event_hash=%s AND owner_token=%s AND status=%s AND expires_at>%d',
            self::tableName(), 'committed', $now + $this->pendingTtlSeconds, $now,
            $this->pendingHash, $this->ownerToken, 'processing', $now
        ));
        if ($updated !== 1) {
            throw new \RuntimeException('Paymos event reservation ownership was lost.');
        }
        $this->clearPending();
    }

    public function release()
    {
        global $wpdb;
        if ($this->pendingHash === '') {
            return;
        }
        self::requireDatabase();
        // phpcs:ignore WordPress.DB.DirectDatabaseQuery -- Release deletes only the current instance's reservation owner.
        $deleted = $wpdb->query($wpdb->prepare('DELETE FROM %i WHERE event_hash=%s AND owner_token=%s AND status=%s', self::tableName(), $this->pendingHash, $this->ownerToken, 'processing'));
        $this->clearPending();
        if ($deleted === false) {
            throw new \RuntimeException('Paymos event reservation release failed.');
        }
    }

    public static function purgeExpired()
    {
        global $wpdb;
        self::ensureTable();
        // Indexed deadline excludes live leases; at most 100 rows per request.
        // phpcs:ignore WordPress.DB.DirectDatabaseQuery -- Prepared indexed cleanup removes at most 100 expired rows.
        if ($wpdb->query($wpdb->prepare('DELETE FROM %i WHERE expires_at<=%d ORDER BY expires_at ASC LIMIT 100', self::tableName(), time())) === false) {
            throw new \RuntimeException('Paymos expired event cleanup failed.');
        }
    }

    private function clearPending()
    {
        $this->pendingHash = '';
        $this->ownerToken = '';
        $this->pendingTtlSeconds = 0;
    }

    private static function ensureTable()
    {
        self::requireDatabase();
        if (get_option(self::SCHEMA_OPTION, '') !== self::SCHEMA_VERSION) {
            self::install();
        }
    }

    private static function requireDatabase()
    {
        global $wpdb;
        foreach (array('query', 'prepare', 'get_row') as $method) {
            if (!is_object($wpdb) || !method_exists($wpdb, $method)) {
                throw new \RuntimeException('Paymos requires durable database event storage.');
            }
        }
    }

    private static function tableName()
    {
        global $wpdb;
        return (string) $wpdb->prefix . 'paymos_edd_webhook_events';
    }
}
